"""A write refusal never sends the user to edit a directive a plugin made (w5/222).

`close_tree` closes a subtree at `<beancount.plugins.close_tree>:0`, and
`check_drained` stamps its balance with the line of the `close` it checks. The
refusals were right, but the remedy said "edit that directive" about the
former and called the latter's `close` line "the existing assertion".
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

HEAD = """\
option "operating_currency" "USD"
{plugin}
2024-01-01 open Assets:Bank USD
2024-01-01 open Assets:Old USD
2024-01-01 open Equity:Opening
2024-01-01 open Expenses:Food USD
2024-01-01 open Expenses:Food:Groceries USD

2024-01-02 * "Opening"
  Assets:Bank  1000.00 USD
  Equity:Opening

2024-01-03 * "Move in"
  Assets:Old  50.00 USD
  Assets:Bank

2024-01-20 * "Move out"
  Assets:Old  -50.00 USD
{meta}  Assets:Bank

"""
#: The line every fixture's last directive lands on.
LAST = 21


def _refused(tmp_path: Path, plugin: str, last: str, *posting: str, meta: str = "") -> str:
    """Run a refused `add transaction`; return its stderr as one line."""
    ledger = tmp_path / "main.bean"
    ledger.write_text(HEAD.format(plugin=f'plugin "{plugin}"' if plugin else "", meta=meta) + last)
    before = ledger.read_bytes()
    env = {k: v for k, v in os.environ.items() if not k.startswith("BEA_") and k != "CI"}
    env.update(
        BEA_CONFIG_DIR=str(tmp_path / "config"),
        XDG_CACHE_HOME=str(tmp_path / "cache"),
        BEA_NO_UPDATE_NOTIFIER="1",
        PYTHONPATH=str(ROOT / "src"),
        NO_COLOR="1",
    )
    result = subprocess.run(
        [sys.executable, "-m", "cli.main", "--file", str(ledger), "add", "transaction", *posting, "-p", "Assets:Bank"],
        env=env,
        stdin=subprocess.DEVNULL,
        capture_output=True,
        text=True,
        timeout=120,
    )
    assert result.returncode == 1, result.stderr
    assert ledger.read_bytes() == before
    return " ".join(result.stderr.split())


GROCERIES = ("--date", "2024-07-01", "Shop", "-p", "Expenses:Food:Groceries 5.00 USD")


def test_plugin_close_names_the_plugin_and_the_written_parent_close(tmp_path: Path) -> None:
    ledger = tmp_path / "main.bean"
    flat = _refused(tmp_path, "beancount.plugins.close_tree", "2024-06-01 close Expenses:Food\n", *GROCERIES)
    assert "Invalid reference to inactive account 'Expenses:Food:Groceries'" in flat
    assert f"Account opened 2024-01-01 at {ledger}:7." in flat
    assert (
        "Account closed 2024-06-01 by plugin beancount.plugins.close_tree, not by a line in the ledger; "
        f"Expenses:Food is closed that day at {ledger}:{LAST}."
    ) in flat
    assert "Correct the transaction date or edit the close of Expenses:Food;" in flat
    assert ">:0" not in flat
    assert "edit that directive" not in flat


def test_written_close_still_points_at_its_line(tmp_path: Path) -> None:
    ledger = tmp_path / "main.bean"
    flat = _refused(tmp_path, "", "2024-06-01 close Expenses:Food:Groceries\n", *GROCERIES)
    assert (
        f"Account opened 2024-01-01 at {ledger}:7. Account closed 2024-06-01 at {ledger}:{LAST}. "
        "Correct the transaction date or edit that directive; for new books use bea init --date YYYY-MM-DD."
    ) in flat
    assert "plugin" not in flat


def test_balance_borrowing_a_close_line_is_not_called_an_assertion(tmp_path: Path) -> None:
    ledger = tmp_path / "main.bean"
    flat = _refused(
        tmp_path,
        "beancount.plugins.check_drained",
        "2024-02-01 close Assets:Old\n",
        *("--date", "2024-01-25", "late", "-p", "Assets:Old 5.00 USD"),
    )
    assert f"{ledger}:{LAST}: Balance failed for 'Assets:Old'" in flat
    assert (
        f"This assertion is generated by a plugin reading the close at {ledger}:{LAST}; "
        "it is not a balance written in the ledger."
    ) in flat
    assert "Review the transactions on Assets:Old before 2024-02-02" in flat
    assert "existing assertion" not in flat
    assert "edit that assertion" not in flat


def test_balance_with_no_source_line_names_its_plugin(tmp_path: Path) -> None:
    flat = _refused(
        tmp_path,
        "beancount.plugins.check_closing",
        "",
        *("--date", "2024-01-15", "late", "-p", "Assets:Old 5.00 USD"),
        meta="    closing: TRUE\n",
    )
    assert "Balance failed for 'Assets:Old'" in flat
    assert "This assertion is generated by plugin check_closing; it is not a balance written in the ledger." in flat
    assert "existing assertion" not in flat
    assert "edit that assertion" not in flat


def test_written_balance_is_still_the_existing_assertion(tmp_path: Path) -> None:
    ledger = tmp_path / "main.bean"
    flat = _refused(
        tmp_path,
        "",
        "2024-02-01 balance Assets:Old 0 USD\n",
        *("--date", "2024-01-25", "late", "-p", "Assets:Old 5.00 USD"),
    )
    assert (
        f"Review transactions against the existing assertion at {ledger}:{LAST}. "
        "Correct missing transactions or edit that assertion; adding another balance would duplicate it."
    ) in flat
    assert "plugin" not in flat
