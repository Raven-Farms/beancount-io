"""Plugin closes point to the responsible plugin and written parent (w5/666)."""

import json
from pathlib import Path

import pytest
from click.testing import Result
from typer.testing import CliRunner

from cli.main import app

runner = CliRunner()
CLOSE_TREE = 'plugin "beancount.plugins.close_tree"\n'
IMPORT_OPENS = (
    "2026-01-01 open Assets:Bank USD\n2026-01-01 open Assets:Bank:Sub USD\n2026-01-01 open Expenses:Food USD\n"
)


def _import(root: Path, source: Path, json_output: bool, *, account: str = "Assets:Bank:Sub") -> Result:
    return runner.invoke(
        app,
        [
            *(["--json"] if json_output else []),
            "--file",
            str(root),
            "import",
            str(source),
            "--csv",
            "auto",
            "--account",
            account,
            "--default-account",
            "Expenses:Food",
        ],
    )


def _blocked_reason(result: Result, json_output: bool) -> str:
    assert result.exit_code == 0, result.output
    if json_output:
        data = json.loads(result.stdout)["data"]
        assert data["blocked"] == 1
        return str(data["rows"][0]["reason"])
    return " ".join(result.output.split())


def _error_details(result: Result, json_output: bool) -> list[str]:
    assert result.exit_code == 1, result.output
    if json_output:
        return list(json.loads(result.stderr)["error"]["details"])
    return [line.strip() for line in result.output.splitlines() if line.strip()]


@pytest.mark.parametrize("json_output", [False, True])
@pytest.mark.parametrize("parent_open", [False, True])
def test_import_after_a_generated_close_names_the_written_parent(
    tmp_path: Path, json_output: bool, parent_open: bool
) -> None:
    root = tmp_path / "main.bean"
    opens = IMPORT_OPENS if parent_open else IMPORT_OPENS.replace("2026-01-01 open Assets:Bank USD\n", "")
    original = CLOSE_TREE + opens + "2026-01-10 close Assets:Bank\n"
    root.write_text(original)
    source = tmp_path / "bank.csv"
    source.write_text("Date,Description,Amount\n2026-01-15,Lunch,-5.00\n")

    reason = _blocked_reason(_import(root, source, json_output), json_output)

    assert "close_tree" in reason
    assert "2026-01-10" in reason
    assert f"{root}:{5 if parent_open else 4}" in reason
    assert "edit the close of Assets:Bank" in reason
    assert ">:0" not in reason
    assert root.read_text() == original


@pytest.mark.parametrize("json_output", [False, True])
def test_import_after_a_written_close_retains_the_direct_remedy(tmp_path: Path, json_output: bool) -> None:
    root = tmp_path / "main.bean"
    original = CLOSE_TREE + IMPORT_OPENS + "2026-01-10 close Assets:Bank:Sub\n"
    root.write_text(original)
    source = tmp_path / "bank.csv"
    source.write_text("Date,Description,Amount\n2026-01-15,Lunch,-5.00\n")

    reason = _blocked_reason(_import(root, source, json_output), json_output)

    assert "Account 'Assets:Bank:Sub' was closed 2026-01-10" in reason
    assert f"{root}:5" in reason
    assert "Re-date the close" in reason
    assert "close_tree" not in reason
    assert root.read_text() == original


@pytest.mark.parametrize("json_output", [False, True])
def test_a_drained_assertion_for_a_generated_close_names_check_drained(tmp_path: Path, json_output: bool) -> None:
    root = tmp_path / "main.bean"
    original = (
        CLOSE_TREE + 'plugin "beancount.plugins.check_drained"\n' + "2026-01-01 open Assets:Bank USD\n"
        "2026-01-01 open Assets:Bank:Sub USD\n"
        "2026-01-01 open Equity:Opening USD\n"
        '2026-01-02 * "Fund"\n'
        "  Assets:Bank:Sub 100 USD\n"
        "  Equity:Opening -100 USD\n"
    )
    root.write_text(original)

    result = runner.invoke(
        app,
        [
            *(["--json"] if json_output else []),
            "--file",
            str(root),
            "add",
            "close",
            "--date",
            "2026-01-10",
            "--account",
            "Assets:Bank",
        ],
    )

    details = _error_details(result, json_output)
    child_index = next(i for i, detail in enumerate(details) if "Balance failed for 'Assets:Bank:Sub'" in detail)
    child_hint = details[child_index + 1]
    assert "check_drained" in child_hint
    assert "Assets:Bank:Sub" in child_hint
    assert "still holds 100 USD" in child_hint
    assert "on or before 2026-01-10" in child_hint
    assert "generated by plugin beancount.plugins.close_tree" not in child_hint
    assert root.read_text() == original


@pytest.mark.parametrize("json_output", [False, True])
@pytest.mark.parametrize("parent_open", [False, True])
def test_a_child_open_after_the_parent_close_names_the_proposed_date_fix(
    tmp_path: Path, json_output: bool, parent_open: bool
) -> None:
    root = tmp_path / "main.bean"
    opened = "2026-01-01 open Assets:Bank USD\n" if parent_open else ""
    original = CLOSE_TREE + opened + "2026-02-01 close Assets:Bank\n"
    root.write_text(original)
    prefix = [*(["--json"] if json_output else []), "--file", str(root), "add", "open"]
    account = ["--account", "Assets:Bank:New", "--currency", "USD"]

    result = runner.invoke(app, [*prefix, "--date", "2026-03-01", *account])

    details = " ".join(_error_details(result, json_output))
    assert "close_tree" in details
    assert "Assets:Bank" in details
    close_line = 3 if parent_open else 2
    assert f"{root}:{close_line}" in details
    assert "on or before 2026-02-01" in details
    assert "another parent" in details
    assert ">:0" not in details
    assert f"{root}:{close_line + 2}" not in details
    assert "date the close on or after" not in details
    assert root.read_text() == original

    # The suggested date correction makes the new account's generated close valid.
    corrected = runner.invoke(app, [*prefix, "--date", "2026-01-15", *account])
    assert corrected.exit_code == 0, corrected.output
    assert "2026-01-15 open Assets:Bank:New USD" in root.read_text()
    checked = runner.invoke(app, ["--json", "--file", str(root), "check"])
    assert checked.exit_code == 0, checked.output


def test_import_recovers_an_nfd_parent_close_for_a_normalized_child(tmp_path: Path) -> None:
    root = tmp_path / "main.bean"
    original = (
        CLOSE_TREE + "2026-01-01 open Assets:Cafe\u0301:Sub USD\n"
        "2026-01-01 open Expenses:Food USD\n"
        "2026-01-10 close Assets:Cafe\u0301\n"
    )
    root.write_text(original)
    source = tmp_path / "bank.csv"
    source.write_text("Date,Description,Amount\n2026-01-15,Lunch,-5.00\n")

    reason = _blocked_reason(_import(root, source, True, account="Assets:Caf\u00e9:Sub"), True)

    assert "close_tree" in reason
    assert f"Assets:Caf\u00e9 is closed that day at {root}:4" in reason
    assert "edit the close of Assets:Caf\u00e9" in reason
    assert ">:0" not in reason
    assert root.read_text() == original


def test_a_late_child_open_recovers_its_nfd_parent_close(tmp_path: Path) -> None:
    root = tmp_path / "main.bean"
    original = CLOSE_TREE + "2026-02-01 close Assets:Cafe\u0301\n"
    root.write_text(original)
    prefix = ["--json", "--file", str(root), "add", "open"]
    account = ["--account", "Assets:Caf\u00e9:New", "--currency", "USD"]

    result = runner.invoke(app, [*prefix, "--date", "2026-03-01", *account])

    details = " ".join(_error_details(result, True))
    assert "close_tree" in details
    assert f"Assets:Caf\u00e9 is closed that day at {root}:2" in details
    assert "on or before 2026-02-01" in details
    assert ">:0" not in details
    assert f"{root}:4" not in details
    assert root.read_text() == original
    corrected = runner.invoke(app, [*prefix, "--date", "2026-01-15", *account])
    assert corrected.exit_code == 0, corrected.output
    checked = runner.invoke(app, ["--json", "--file", str(root), "check"])
    assert checked.exit_code == 0, checked.output
