"""A stray CR in the ledger does not change how a new entry's errors read (w5/380).

The write path split the original files with `bytes.splitlines()`, which also
breaks on a lone `\\r`, so the file looked longer than Beancount's lexer counts
it. The appended entry then sat inside the "original" range: a failed balance
was blamed on a plugin, errors lost `Proposed append (not written)`, and the
documented `add pad --allow-errors` step was refused.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
BODY = (
    b'option "operating_currency" "USD"\n'
    b"; pasted note: a\rb\rc\rd\re\rf\rg\rh\n"
    b"2026-01-01 open Assets:Cash USD\n"
    b"2026-01-01 open Equity:Opening USD\n"
    b'2026-01-02 * "seed"\n'
    b"  Assets:Cash 100 USD\n"
    b"  Equity:Opening\n"
)
LEDGERS = {"lone-cr": BODY, "cr-cr-lf": BODY.replace(b"\r", b" ").replace(b"\n", b"\r\r\n")}


def _bea(tmp_path: Path, *args: str) -> subprocess.CompletedProcess[str]:
    env = {k: v for k, v in os.environ.items() if not k.startswith("BEA_")}
    env.update(
        BEA_CONFIG_DIR=str(tmp_path / "config"),
        XDG_CACHE_HOME=str(tmp_path / "cache"),
        BEA_NO_UPDATE_NOTIFIER="1",
        PYTHONPATH=str(ROOT / "src"),
        TERM="dumb",
        NO_COLOR="1",
    )
    return subprocess.run(
        [sys.executable, "-m", "cli.main", "-f", "main.bean", *args],
        env=env,
        cwd=tmp_path,
        capture_output=True,
        text=True,
        timeout=120,
        stdin=subprocess.DEVNULL,
    )


@pytest.fixture(params=sorted(LEDGERS))
def ledger(request: pytest.FixtureRequest, tmp_path: Path) -> Path:
    file = tmp_path / "main.bean"
    file.write_bytes(LEDGERS[request.param])
    assert _bea(tmp_path, "check").returncode == 0
    return file


def test_a_failed_balance_reads_as_the_proposed_append(ledger: Path) -> None:
    before = ledger.read_bytes()

    result = _bea(
        ledger.parent, "add", "balance", "--date", "2026-02-01", "--account", "Assets:Cash", "--amount", "50 USD"
    )

    assert result.returncode == 1
    assert "Proposed append (not written): Balance failed" in result.stderr
    assert "generated by a plugin" not in result.stderr
    assert "Balance assertions run at the start of the day" in result.stderr
    assert ledger.read_bytes() == before


def test_an_unknown_account_reads_as_the_proposed_append(ledger: Path) -> None:
    result = _bea(
        ledger.parent,
        "add",
        "transaction",
        "X",
        "--date",
        "2026-02-01",
        "-p",
        "Expenses:Nope 5 USD",
        "-p",
        "Assets:Cash",
    )

    assert result.returncode == 1
    assert "Proposed append (not written): Invalid reference to unknown account" in result.stderr


def test_the_two_step_pad_flow_still_starts(ledger: Path) -> None:
    result = _bea(
        ledger.parent,
        *("add", "pad", "--date", "2026-02-01", "--account", "Assets:Cash", "--source", "Equity:Opening"),
        "--allow-errors",
    )

    assert result.returncode == 0, result.stderr
    assert "Added 1 pad" in result.stdout + result.stderr
